"""Verify completed R1 evidence and write an immutable numerical brief."""
import argparse
import csv
import json
from pathlib import Path

from runtime.common import configure_ultralytics, file_hash, write_json
from tools.inspect_a2_selection import infer_selection


def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run', default='experiments/p2_r1_resolution320_retry1')
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    root, output = Path(args.run), Path(args.output)
    if output.exists() or (root/'verification.json').exists():
        raise FileExistsError('Report or verification already exists')
    report = read(root/'report.json')
    if report['status'] != 'complete' or report['actual_recipe_check'] != 'passed':
        raise ValueError('R1 must finish successfully first')
    if read(root/'evaluation/data_audit.json') != read('experiments/p2_expanded_new_evaluation/data_audit.json'):
        raise AssertionError('Common evaluation dataset changed')
    old = read('experiments/p2_expanded_new_review/review.json')
    rebuilt = read(root/'reference_review/review.json')
    for key in ('totals', 'size_counts', 'predictions_sha256', 'model_sha256'):
        if old[key] != rebuilt[key]:
            raise AssertionError(f'Rebuilt reference changed: {key}')
    if file_hash('training/baseline.py') != read(root/'train/report.json')['entrypoint_sha256']:
        raise AssertionError('Training source changed after experiment began')
    with Path('experiments/p2_r1_resolution320/train/fit/results.csv').open(encoding='utf-8') as stream:
        interrupted_first = next(csv.DictReader(stream))
    with (root/'train/fit/results.csv').open(encoding='utf-8') as stream:
        restarted_first = next(csv.DictReader(stream))
    if any(interrupted_first[k] != restarted_first[k] for k in interrupted_first if k != 'time'):
        raise AssertionError('Restart first epoch differs from interrupted run')
    # Use only the checkpoint generated by this local experiment, never arbitrary downloads.
    configure_ultralytics()
    import torch
    torch.set_num_threads(1)
    checkpoint = torch.load(root/'train/fit/weights/best.pt', map_location='cpu', weights_only=False)
    with (root/'train/fit/results.csv').open(encoding='utf-8') as stream:
        selection = infer_selection(checkpoint.get('train_metrics', {}), list(csv.DictReader(stream)))
    verification = {'status': 'complete', 'common_data_audit': 'identical',
                    'rebuilt_reference': 'identical counts and prediction/model hashes',
                    'training_source': 'unchanged', 'restart_first_epoch': 'identical except elapsed time', 'candidate_selection': selection,
                    'candidate_sha256': file_hash(root/'train/fit/weights/best.pt')}
    if verification['candidate_sha256'] != report['candidate_model_sha256']:
        raise AssertionError('Candidate weights changed')
    write_json(root/'verification.json', verification)
    a, b, c = report['reference_validation'], report['candidate_validation'], report['comparison']
    lines = ['# P2 R1 配套 320 分辨率实验简报', '',
             '2026-09-27。50 轮训练、共同开发验证、固定工作点推理及逐图对照已完成。', '',
             '按 [训练前计划](P2_R1实验计划.md)，唯一配方变化为输入 128 → 320。训练数据、初始化、种子、batch、优化器及增强配置一致；实际参数检查通过。50 轮 Mosaic 均启用。', '',
             '## 共同 109 张开发图', '', '| 指标 | 原 128 | R1 320 |', '|---|---:|---:|']
    for name, key in [('mAP50', 'metrics/mAP50(B)'), ('mAP50:95', 'metrics/mAP50-95(B)')]:
        lines.append(f"| {name} | {a['aggregate'][key]:.2%} | {b['aggregate'][key]:.2%} |")
    for name in ('smoke', 'fire'):
        lines.append(f"| {name} AP50 | {a['per_class'][name]['ap50']:.2%} | {b['per_class'][name]['ap50']:.2%} |")
    lines += ['', '114 张训练验证图用于选择 best；上述 109 张是反复使用的共同开发图，非独立测试。AP 使用库内 conf=0.001、NMS=0.7。', '',
              '## 固定工作点', '', 'conf=0.25、NMS IoU=0.45、同类匹配 IoU=0.5。框均还原原图坐标。', '',
              '| 类别 | 原 TP/FP/FN | R1 TP/FP/FN |', '|---|---:|---:|']
    for name in ('smoke', 'fire'):
        values = ['/'.join(str(c[side+'_totals'][name][key]) for key in ('tp','fp','fn')) for side in ('old','new')]
        lines.append(f'| {name} | {values[0]} | {values[1]} |')
    n = c['negative_images']
    lines += ['', f"补检 {c['recovered_targets']} 个、丢失 {c['lost_targets']} 个。{n['images']} 张负样本中有预测的图片：{n['old_with_predictions']} → {n['new_with_predictions']}。框误检与图片误检均不是事件报警率。", '',
              '| 类别 | 128 参考短边组 | GT | 原检出 | R1 检出 |', '|---|---|---:|---:|---:|']
    for name in ('smoke','fire'):
        for bucket in ('lt8','8to16','ge16'):
            x,y = c['old_size_counts'][name][bucket], c['new_size_counts'][name][bucket]
            if x['gt'] != y['gt']: raise AssertionError('Target group population changed')
            lines.append(f"| {name} | {bucket} | {x['gt']} | {x['tp']} | {y['tp']} |")
    import os
    link = Path(os.path.relpath(root, output.parent)).as_posix()
    lines += ['', '短边始终按原图像素 × 128 / 原图最长边计算，分组不随模型输入改变；lt8、8to16、ge16 对应 <8、8～<16、≥16 像素。', '',
              '## 证据与限制', '',
              f"- [总报告]({link}/report.json)、[最终来源核验]({link}/verification.json)、[逐图对照]({link}/comparison.html)。",
              '- [65 项回归测试](p2_r1_recovery_tests.log)通过，包括跨尺寸显式授权、NMS、固定分组、几何一致性及 Windows 架构元数据恢复检查。',
              f"- 原权重 SHA256：`{report['reference_model_sha256']}`。",
              f"- R1 权重 SHA256：`{report['candidate_model_sha256']}`。",
              f"- 最佳权重保存指标唯一对应轮次：{selection['epoch']}；这是指标匹配推断，不采用 checkpoint 完整历史长度。", '',
              '首次训练在第 1 轮保存时因 Polars 报错 `unknown feature flag: sse3` 中断，根因是启动环境遗漏 PROCESSOR_ARCHITECTURE，Python 返回空架构。修复从 Windows IsWow64Process2 读取真实架构，未跳过 CPU 检查、未修改依赖库。失败目录 [保留原日志](p2_r1_resolution320/training.log)；本次在 retry1 从相同初始化重新训练，首轮所有已保存指标/损失/学习率与失败运行一致（排除耗时）。', '',
              '本次为单种子对历史基线的比较，未证明跨种子稳定性或校园泛化。16 张 test 未推理；未采购硬件、未采集真实数据、未修改 P3 或自动推广模型。CPU 耗时仅表示本机软件开销。']
    output.write_text('\n'.join(lines)+'\n', encoding='utf-8')


if __name__ == '__main__':
    main()
